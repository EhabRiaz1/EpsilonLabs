#!/usr/bin/env node
// Generates api/_email-layout.js (CommonJS, for the site's Vercel function) from the one email layout source,
// platform/lib/email/layout-core.mjs. The site deploy excludes platform/, so api/ needs its own copy; this keeps it
// a faithful one. platform/lib/email/layout-sync.test.ts fails when the committed copy is stale.
//
//   node tools/build-email-layout.mjs           # write api/_email-layout.js
//   node tools/build-email-layout.mjs --check   # exit 1 if it is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE = join(ROOT, "platform/lib/email/layout-core.mjs");
export const TARGET = join(ROOT, "api/_email-layout.js");

/** ESM source text -> CommonJS text. Only `export function` / `export const` are allowed in the source. */
export function build(src) {
  const names = [];
  const body = src.replace(/^export (function|const) ([A-Za-z_$][\w$]*)/gm, (_, kind, name) => {
    names.push(name);
    return `${kind} ${name}`;
  });
  const left = body.match(/^\s*(export|import)\b.*$/m);
  if (left) throw new Error(`layout-core.mjs: unsupported module syntax for the CommonJS build: ${left[0].trim()}`);
  return (
    "// GENERATED by tools/build-email-layout.mjs from platform/lib/email/layout-core.mjs. Do not edit by hand:\n" +
    "// edit the source and run `node tools/build-email-layout.mjs`. The leading underscore keeps Vercel from deploying\n" +
    "// this file as its own function.\n" +
    "'use strict';\n\n" +
    body.trimEnd() +
    `\n\nmodule.exports = {\n${names.map((n) => `  ${n},`).join("\n")}\n};\n`
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = build(readFileSync(SOURCE, "utf8"));
  if (process.argv.includes("--check")) {
    let cur = "";
    try {
      cur = readFileSync(TARGET, "utf8");
    } catch {
      cur = "";
    }
    if (cur !== out) {
      console.error("api/_email-layout.js is stale: run node tools/build-email-layout.mjs");
      process.exit(1);
    }
    console.log("api/_email-layout.js is up to date");
  } else {
    writeFileSync(TARGET, out);
    console.log(`wrote ${TARGET}`);
  }
}
